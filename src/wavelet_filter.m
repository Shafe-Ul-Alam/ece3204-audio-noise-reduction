function h = wavelet_filter(name)
% WAVELET_FILTER  Orthogonal scaling (low-pass) filter of common wavelets.
%   Coefficients are the standard values (sum(h) = sqrt(2), sum(h.^2) = 1).
%   Families covered in the lab: Haar, Daubechies, Symlets, Coiflets.
switch lower(name)
    case {'haar', 'db1'}
        h = [1; 1] / sqrt(2);
    case 'db2'
        h = [0.48296291314453416; 0.8365163037378079; 0.2241438680420134; -0.12940952255126037];
    case 'db4'
        h = [0.2303778133088965; 0.7148465705529157; 0.6308807679298589; -0.027983769416859854;
            -0.18703481171909309; 0.030841381835560764; 0.0328830116668852; -0.010597401785069032];
    case 'db8'
        h = [0.05441584224310401; 0.31287159091429995; 0.6756307362972898; 0.5853546836542067;
            -0.015829105256349306; -0.2840155429615469; 0.0004724845739132828; 0.12874742662047847;
            -0.017369301001807547; -0.044088253930794755; 0.013981027917398282; 0.008746094047405777;
            -0.004870352993451574; -0.00039174037337694705; 0.0006754494064505693; -0.00011747678412476953];
    case 'sym4'
        h = [0.0322231006040427; -0.012603967262037833; -0.09921954357684722; 0.29785779560527736;
             0.8037387518059161; 0.49761866763201545; -0.02963552764599851; -0.07576571478927333];
    case 'coif1'
        h = [-0.07273261951252645; 0.3378976624574818; 0.8525720202116004; 0.3848648468648578;
             -0.07273261951252645; -0.015655728135791993];
    otherwise
        error('Unknown wavelet: %s', name);
end
end
